"""Форматирование чисел для русскоязычных отчётов и журналов."""

from __future__ import annotations


def fmt_rub(amount: float, decimals: int = 2) -> str:
    """Сумма в рублях с пробелами между тысячами: 20 000.00.

    Заменяет запятые-разделители только внутри числа, не трогая
    пунктуацию окружающего текста.
    """
    return f"{amount:,.{decimals}f}".replace(",", " ")
