"""ML-модули — ЧАСТЬ II ТЗ. Выключены фича-флагом ``ml.enabled: false``.

Флаг переводится в true только при одновременном выполнении всех условий
раздела 24 ТЗ (фазы 1–8 пройдены, 3 месяца бумажной торговли, purged
K-Fold и PBO покрыты тестами и т.д.). До этого модули существуют,
покрываются тестами на синтетических данных, но в торговом контуре
не участвуют.
"""

from __future__ import annotations


class MlDisabledError(Exception):
    """Попытка использовать ML при выключенном фича-флаге."""


def ensure_ml_enabled(settings) -> None:
    """Вызывается в начале любого ML-пайплайна. Флаг выключен → ошибка."""
    if not settings.ml.enabled:
        raise MlDisabledError(
            "ML выключен (ml.enabled: false). Включение возможно только после "
            "выполнения всех условий раздела 24 ТЗ: фазы 1–8 пройдены, "
            "3 месяца бумажной торговли без расхождений, purged K-Fold и PBO "
            "реализованы и покрыты тестами."
        )
